val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val releaseStoreFile = if (keystorePropertiesFile.isFile) {
    keystorePropertiesFile.reader(Charsets.UTF_8).use { keystoreProperties.load(it) }
    val rawStoreFile = keystoreProperties.getProperty("storeFile")?.trim().orEmpty()
    if (rawStoreFile.isNotEmpty()) {
        val appRelativeOrAbs = file(rawStoreFile)
        if (appRelativeOrAbs.isFile) appRelativeOrAbs else rootProject.file(rawStoreFile)
    } else {
        null
    }
} else {
    null
}
val hasReleaseSigning = releaseStoreFile != null &&
    releaseStoreFile.isFile &&
    !keystoreProperties.getProperty("keyAlias").isNullOrBlank() &&
    !keystoreProperties.getProperty("keyPassword").isNullOrBlank() &&
    !keystoreProperties.getProperty("storePassword").isNullOrBlank()

